using System;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Sidekick.Localization.Generators;

/// <summary>
/// Generates a typed member on IStringLocalizer&lt;T&gt; for each key of T.resx, so Resources["Open_Website"] can be written Resources.Open_Website and a missing key does not compile.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LocalizerExtensionsGenerator : IIncrementalGenerator
{
    private const string LocalizerMetadataName = "Microsoft.Extensions.Localization.IStringLocalizer`1";

    private static readonly string[] LocalizerMembers = ["GetAllStrings", "GetString", "WithCulture"];

    /// <summary>
    /// Instance members win over extension members, so a member with one of these names could never be called. Keys like these come from enum values (AutoSelectComparisonType.Equals) and are read with the indexer.
    /// </summary>
    private static readonly string[] ObjectMembers = ["Equals", "GetHashCode", "GetType", "ToString"];

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var project = context.AnalyzerConfigOptionsProvider.Select((provider, _) =>
        {
            provider.GlobalOptions.TryGetValue("build_property.RootNamespace", out var rootNamespace);
            provider.GlobalOptions.TryGetValue("build_property.ProjectDir", out var projectDirectory);
            provider.GlobalOptions.TryGetValue("build_property.SharedLocalizationResources", out var sharedResources);
            return new ProjectInfo(rootNamespace ?? string.Empty, projectDirectory ?? string.Empty, sharedResources ?? string.Empty);
        });

        var files = context.AdditionalTextsProvider
            .Where(text => ResxFile.IsBase(text.Path))
            .Select((text, cancellationToken) => ResxFile.Parse(text.Path, text.GetText(cancellationToken)?.ToString()));

        var targets = files
            .Combine(context.CompilationProvider)
            .Select((pair, _) => (File: pair.Left, Target: FindTarget(pair.Right, pair.Left)))
            .Combine(project);

        context.RegisterSourceOutput(targets, (productionContext, pair) => Generate(productionContext, pair.Left.File, pair.Left.Target, pair.Right));
    }

    private static TargetType? FindTarget(Compilation compilation, ResxFile file)
    {
        if (compilation.GetTypeByMetadataName(LocalizerMetadataName) == null)
        {
            return null;
        }

        var candidates = compilation.GetSymbolsWithName(file.ClassName, SymbolFilter.Type)
            .OfType<INamedTypeSymbol>()
            .Where(x => !x.IsGenericType)
            .ToList();

        var directory = Path.GetDirectoryName(file.Path);
        var symbol = candidates.FirstOrDefault(x => x.DeclaringSyntaxReferences.Any(reference => string.Equals(Path.GetDirectoryName(reference.SyntaxTree.FilePath), directory, StringComparison.OrdinalIgnoreCase)));
        if (symbol == null)
        {
            // Razor components (Setup.razor) are generated by another generator, so their type is not visible here. Fall back to the namespace Razor derives from the folder.
            return new TargetType(Namespace: null, FullName: null, IsPublic: true);
        }

        var isPublic = true;
        for (var type = symbol; type != null; type = type.ContainingType)
        {
            if (type.DeclaredAccessibility != Accessibility.Public)
            {
                isPublic = false;
            }
        }

        var containingNamespace = symbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : symbol.ContainingNamespace.ToDisplayString();
        return new TargetType(containingNamespace, symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), isPublic);
    }

    private static void Generate(SourceProductionContext context, ResxFile file, TargetType? target, ProjectInfo project)
    {
        if (target == null)
        {
            return;
        }

        if (file.Error != null)
        {
            context.ReportDiagnostic(Diagnostic.Create(LocalizationDiagnostics.UnreadableFile, Location.None, Path.GetFileName(file.Path), file.Error));
            return;
        }

        var @namespace = target.Namespace ?? GetFolderNamespace(file.Path, project);
        var fullName = target.FullName ?? (@namespace.Length == 0 ? $"global::{file.ClassName}" : $"global::{@namespace}.{file.ClassName}");
        var fileName = Path.GetFileName(file.Path);

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        if (@namespace.Length > 0)
        {
            builder.AppendLine($"namespace {@namespace};");
            builder.AppendLine();
        }

        builder.AppendLine($"/// <summary>Typed keys of {Escape(fileName)}.</summary>");
        var isPublic = target.IsPublic && project.IsShared(file.ClassName);
        builder.AppendLine($"{(isPublic ? "public" : "internal")} static class {file.ClassName}LocalizerExtensions");
        builder.AppendLine("{");
        builder.AppendLine($"    extension(global::Microsoft.Extensions.Localization.IStringLocalizer<{fullName}> localizer)");
        builder.AppendLine("    {");

        var first = true;
        foreach (var entry in file.Entries)
        {
            if (!SyntaxFacts.IsValidIdentifier(entry.Key))
            {
                context.ReportDiagnostic(Diagnostic.Create(LocalizationDiagnostics.InvalidKey, GetLocation(file, entry), entry.Key, fileName));
                continue;
            }

            if (LocalizerMembers.Contains(entry.Key))
            {
                context.ReportDiagnostic(Diagnostic.Create(LocalizationDiagnostics.ConflictingKey, GetLocation(file, entry), entry.Key, fileName));
                continue;
            }

            if (ObjectMembers.Contains(entry.Key))
            {
                context.ReportDiagnostic(Diagnostic.Create(LocalizationDiagnostics.ObjectMemberKey, GetLocation(file, entry), entry.Key, fileName));
                continue;
            }

            if (!first)
            {
                builder.AppendLine();
            }

            first = false;
            AppendMember(builder, entry);
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");

        var hintName = @namespace.Length == 0 ? file.ClassName : $"{@namespace}.{file.ClassName}";
        context.AddSource($"{hintName}.Localization.g.cs", builder.ToString());
    }

    private static void AppendMember(StringBuilder builder, ResxEntry entry)
    {
        var lines = entry.Value.Replace("\r\n", "\n").Split('\n');
        builder.AppendLine("        /// <summary>");
        foreach (var line in lines)
        {
            builder.AppendLine($"        /// {Escape(line)}");
        }

        builder.AppendLine("        /// </summary>");

        var name = SyntaxFacts.GetKeywordKind(entry.Key) != SyntaxKind.None ? "@" + entry.Key : entry.Key;
        var key = SymbolDisplay.FormatLiteral(entry.Key, quote: true);
        var argumentCount = entry.ArgumentCount;
        if (argumentCount == 0)
        {
            builder.AppendLine($"        public string {name} => localizer[{key}];");
            return;
        }

        var parameters = string.Join(", ", Enumerable.Range(0, argumentCount).Select(i => $"object arg{i}"));
        var arguments = string.Join(", ", Enumerable.Range(0, argumentCount).Select(i => $"arg{i}"));
        builder.AppendLine($"        public string {name}({parameters}) => localizer[{key}, {arguments}];");
    }

    private static string GetFolderNamespace(string path, ProjectInfo project)
    {
        var directory = Path.GetDirectoryName(path) ?? string.Empty;
        var projectDirectory = project.Directory.TrimEnd('/', '\\');
        var relative = projectDirectory.Length > 0 && directory.StartsWith(projectDirectory, StringComparison.OrdinalIgnoreCase)
            ? directory.Substring(projectDirectory.Length)
            : string.Empty;

        var parts = new[] { project.RootNamespace }
            .Concat(relative.Split(['/', '\\'], StringSplitOptions.RemoveEmptyEntries))
            .Where(x => x.Length > 0);

        return string.Join(".", parts);
    }

    private static Location GetLocation(ResxFile file, ResxEntry entry)
    {
        var position = new LinePosition(Math.Max(entry.Line - 1, 0), Math.Max(entry.Column - 1, 0));
        return Location.Create(file.Path, default, new LinePositionSpan(position, position));
    }

    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private sealed record ProjectInfo(string RootNamespace, string Directory, string SharedResources)
    {
        /// <summary>
        /// Only shared resources (UiResources) get public members, so other projects can't use a project's own resources (issue #1324).
        /// </summary>
        public bool IsShared(string className) => SharedResources
            .Split([';', ','], StringSplitOptions.RemoveEmptyEntries)
            .Any(x => x.Trim() == className);
    }

    private sealed record TargetType(string? Namespace, string? FullName, bool IsPublic);
}
